let cgvLanguage = "es";

function interpolate(value, params = {}) {
  return String(value || "").replace(/\{(\w+)\}/g, (_match, key) => params[key] ?? "");
}

function t(key, params = {}) {
  return interpolate(CGV_TRANSLATIONS[cgvLanguage]?.[key] || CGV_TRANSLATIONS.es[key] || key, params);
}

function setCgvLanguage(language) {
  cgvLanguage = ["es", "en"].includes(language) ? language : "es";
  document.documentElement.lang = cgvLanguage;
  window.CGV_LANGUAGE = cgvLanguage;
  translatePage();
}

function translatePage(root = document) {
  root.querySelectorAll("[data-i18n]").forEach(element => {
    element.textContent = t(element.dataset.i18n);
  });

  root.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    element.setAttribute("placeholder", t(element.dataset.i18nPlaceholder));
  });

  root.querySelectorAll("[data-i18n-title]").forEach(element => {
    element.setAttribute("title", t(element.dataset.i18nTitle));
  });

  root.querySelectorAll("[data-i18n-aria-label]").forEach(element => {
    element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
  });

  root.querySelectorAll("[data-i18n-alt]").forEach(element => {
    element.setAttribute("alt", t(element.dataset.i18nAlt));
  });

  const titleKey = document.querySelector("title")?.dataset.i18n;
  if (titleKey) document.title = t(titleKey);
}

async function loadCgvLanguage() {
  try {
    const response = await fetch("/style-settings");
    const settings = response.ok ? await response.json() : {};
    setCgvLanguage(settings.language || "es");
  } catch {
    setCgvLanguage("es");
  }
}

window.CGVI18N = { t, setLanguage: setCgvLanguage, loadLanguage: loadCgvLanguage, translatePage };
window.t = t;
